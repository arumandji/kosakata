// FUNGSI MENAMPILKAN & MENYARING KOSAKATA
function renderVocab() {
    let searchKeyword = document.getElementById('searchInput').value.toLowerCase();
    let listContainer = document.getElementById('vocabList');
    
    listContainer.innerHTML = ""; 

    let filteredData = vocabData.filter(item => {
        let textGabung = (item.no + item.jp + (item.kanji || "") + item.arti + item.bab).toLowerCase();
        return textGabung.includes(searchKeyword);
    });

    if (filteredData.length === 0) {
        listContainer.innerHTML = "<p style='text-align:center; color:#888;'>Kosakata tidak ditemukan...</p>";
        return;
    }

    filteredData.forEach(item => {
        let card = document.createElement('div');
        card.className = 'vocab-card';
        card.innerHTML = `
            <div style="display: flex; gap: 8px; align-items: center; width: 100%; justify-content: space-between;">
                <div style="display: flex; gap: 8px; align-items: center; min-width: 0;">
                    <span style="font-size: 12px; font-weight: 600; color: #aaa; flex-shrink: 0;">${item.no}</span>
                    <div style="min-width: 0;">
                        <div class="jp" style="font-size: 15px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis;">
                            ${item.jp} 
                            ${item.kanji !== "-" ? `<span style="font-size: 12px; color: #d9534f; font-weight: normal; margin-left: 4px;">(${item.kanji})</span>` : ""}
                        </div>
                        <div class="romaji" style="font-size: 12px; white-space: nowrap; overflow: hidden; text-overflow: ellipsis;">${item.arti}</div>
                    </div>
                </div>
                <div class="badge" style="flex-shrink: 0; font-size: 11px; padding: 2px 6px;">${item.bab}</div>
            </div>
        `;
        listContainer.appendChild(card);
    });
}

renderVocab();